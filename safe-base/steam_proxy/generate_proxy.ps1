# generate_proxy.ps1 — produce steam_proxy.cpp and steam_proxy.def from exports.txt.
# exports.txt was created with `dumpbin /exports <real steam_api64.dll>` and
# contains one export name per line. Regenerate it if the game updates its
# Steamworks SDK. Do not hand-edit steam_proxy.{cpp,def}; edit exports.txt +
# rerun this script.

$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

$names = Get-Content 'exports.txt' | Where-Object { $_ -and $_.Trim() } | ForEach-Object { $_.Trim() } | Sort-Object -Unique
if (-not $names -or $names.Count -eq 0) { throw "exports.txt is empty" }

# Names the real DLL exports as DATA (a global), not as a function.
$dataExports = @('g_pSteamClientGameServer')

# ---------------------------------------------------------------------------
# steam_proxy.def - one entry per export so the linker emits a table matching
# what the game expects to see when it imports steam_api64.dll.
# ---------------------------------------------------------------------------
$def = New-Object System.Collections.Generic.List[string]
$def.Add('; Auto-generated from exports.txt - do not hand-edit.')
$def.Add('; Regenerate with: powershell -File generate_proxy.ps1')
$def.Add('LIBRARY steam_api64')
$def.Add('EXPORTS')
foreach ($n in $names) { $def.Add("  $n") }
Set-Content -Path 'steam_proxy.def' -Value $def -Encoding ASCII

# ---------------------------------------------------------------------------
# steam_proxy.cpp - every function returns 0 (bool false, NULL pointer, zero
# HSteamPipe). x64 calling convention means a (void) parameter list still
# accepts whatever the caller pushes; the register/stack args are simply
# ignored. Larger-than-8-byte struct returns leave the caller's return-buffer
# untouched (zeroed by the game's alloc), which is what "no data" looks like.
# ---------------------------------------------------------------------------
$cpp = New-Object System.Collections.Generic.List[string]
$cpp += '// Auto-generated by generate_proxy.ps1 from exports.txt'
$cpp += '// (dumpbin /exports of the real steam_api64.dll).'
$cpp += '//'
$cpp += '// Purpose: a safe-base "offline mode" proxy. Every export is a stub'
$cpp += '// that returns 0 (false / NULL / HSteamPipe=0). SteamAPI_InitFlat and'
$cpp += '// SteamInternal_SteamAPI_Init return false, so Steamworks.NET never'
$cpp += '// obtains an ISteamUserStats to call UploadLeaderboardScore on, and'
$cpp += '// the game goes through its "no Steam" code path. Nothing here calls'
$cpp += '// into Steam; the DLL is inert.'
$cpp += '//'
$cpp += '// Do not hand-edit. Edit exports.txt and rerun generate_proxy.ps1.'
$cpp += ''
$cpp += '#include <windows.h>'
$cpp += ''
$cpp += '#define STUB_FN(name) \'
$cpp += '    extern "C" __declspec(dllexport) unsigned long long name(void) { return 0ULL; }'
$cpp += ''
$cpp += '// Data export (real DLL exports this as a global, not a function).'
$cpp += 'extern "C" __declspec(dllexport) void* g_pSteamClientGameServer = nullptr;'
$cpp += ''
foreach ($n in $names) {
    if ($dataExports -contains $n) { continue }
    $cpp += "STUB_FN($n)"
}
$cpp += ''
$cpp += 'BOOL WINAPI DllMain(HINSTANCE, DWORD, LPVOID) { return TRUE; }'
Set-Content -Path 'steam_proxy.cpp' -Value $cpp -Encoding ASCII

Write-Host "generated steam_proxy.cpp + steam_proxy.def"
Write-Host "  total exports: $($names.Count)"
Write-Host "  data exports:  $($dataExports.Count) ($($dataExports -join ', '))"
Write-Host "  fn stubs:      $($names.Count - $dataExports.Count)"
